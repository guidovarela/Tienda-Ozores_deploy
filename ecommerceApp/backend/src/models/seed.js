async function getOrCreateCategoria(Categoria, nombre) {
  let categoria = await Categoria.findOne({ where: { nombre } });
  if (!categoria) {
    categoria = await Categoria.create({ nombre });
  }
  return categoria;
}

async function getOrCreateUsuario(Usuario, userData) {
  const usuario = await Usuario.findOne({ where: { email: userData.email } });
  if (!usuario) {
    await Usuario.create(userData);
  }
}

async function getOrCreateProducto(Producto, productoData) {
  const existente = await Producto.findOne({ where: { nombre: productoData.nombre } });
  if (!existente) {
    await Producto.create(productoData);
  }
}

async function getOrCreateCupon(Cupon, cuponData) {
  const existente = await Cupon.findOne({ where: { nombre: cuponData.nombre } });
  if (!existente) {
    await Cupon.create(cuponData);
  }
}

